package com.vitalai.data.mapper

import com.vitalai.data.local.room.entity.ExerciseEntity
import com.vitalai.data.remote.model.ExerciseDto

fun ExerciseEntity.toDto() = ExerciseDto(
    id = id,
    name = name,
    primaryMuscleGroup = primaryMuscleGroup,
    muscleGroupRaw = muscleGroupRaw,
    category = category,
    difficultyLevel = difficultyLevel,
    equipment = equipment,
    description = description,
    instructions = instructions,
    formTips = formTips,
    intensity = intensity,
    thumbnailUrl = thumbnailUrl,
    videoUrl = videoUrl,
    imageAvtUrl = imageAvtUrl,
    imageUrl = imageUrlsPiped?.split("|")?.filter { it.isNotEmpty() }?.takeIf { it.isNotEmpty() },
    metValue = metValue,
    caloriesPerMin = caloriesPerMin,
    estimatedCaloriesPerMinute = estimatedCaloriesPerMinute,
    favoritesCount = favoritesCount,
    isFavorite = isFavorite,
    secondaryMuscleGroups = secondaryMuscleGroupsPiped?.split("|")?.filter { it.isNotEmpty() }?.takeIf { it.isNotEmpty() },
    defaultSets = defaultSets,
    defaultReps = defaultReps,
    defaultWeightKg = defaultWeightKg,
    targetMuscleGroup = targetMuscleGroup,
    restTimeSeconds = restTimeSeconds,
    defaultDurationMinutes = defaultDurationMinutes,
    defaultIntensityLevel = defaultIntensityLevel,
    movementType = movementType,
    exerciseType = exerciseType
)

fun ExerciseDto.toEntity(isFavorite: Boolean = this.isFavorite) = ExerciseEntity(
    id = id,
    name = name,
    primaryMuscleGroup = primaryMuscleGroup,
    muscleGroupRaw = muscleGroupRaw,
    category = category,
    difficultyLevel = difficultyLevel,
    equipment = equipment,
    description = description,
    instructions = instructions,
    formTips = formTips,
    intensity = intensity,
    thumbnailUrl = thumbnailUrl,
    videoUrl = videoUrl,
    imageAvtUrl = imageAvtUrl,
    imageUrlsPiped = imageUrl?.filter { it.isNotEmpty() }?.joinToString("|"),
    metValue = metValue,
    caloriesPerMin = caloriesPerMin,
    estimatedCaloriesPerMinute = estimatedCaloriesPerMinute,
    favoritesCount = favoritesCount,
    isFavorite = isFavorite,
    secondaryMuscleGroupsPiped = secondaryMuscleGroups?.filter { it.isNotEmpty() }?.joinToString("|"),
    defaultSets = defaultSets,
    defaultReps = defaultReps,
    defaultWeightKg = defaultWeightKg,
    targetMuscleGroup = targetMuscleGroup,
    restTimeSeconds = restTimeSeconds,
    defaultDurationMinutes = defaultDurationMinutes,
    defaultIntensityLevel = defaultIntensityLevel,
    movementType = movementType,
    exerciseType = exerciseType
)
